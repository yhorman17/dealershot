-- Expand the existing account-access mutation to the approved administrator
-- scope. Owner access stays global; dealer administrators may edit only staff
-- in one of their currently active assigned dealerships.
CREATE OR REPLACE FUNCTION public.admin_update_user_account_access(
  _actor_user_id uuid,
  _target_user_id uuid,
  _full_name text,
  _role public.app_role,
  _dealership_ids uuid[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_role public.app_role;
  target_primary uuid;
  assignment_count integer := COALESCE(cardinality(_dealership_ids), 0);
BEGIN
  IF _actor_user_id = _target_user_id THEN
    RAISE EXCEPTION 'Use profile settings to change your own name.';
  END IF;
  SELECT role, dealership_id INTO target_role, target_primary
  FROM public.profiles WHERE id = _target_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'User not found'; END IF;
  IF target_role = 'owner'::public.app_role THEN
    RAISE EXCEPTION 'Owner roles cannot be changed through user administration.';
  END IF;
  PERFORM private.validate_dealer_account_scope(_actor_user_id, _role, _dealership_ids);
  IF NOT (SELECT private.actor_is_active_owner(_actor_user_id)) THEN
    IF target_role <> 'staff'::public.app_role OR _role <> 'staff'::public.app_role
       OR assignment_count <> 1
       OR NOT (SELECT private.actor_is_active_dealer_admin_for(_actor_user_id, target_primary)) THEN
      RAISE EXCEPTION 'Forbidden';
    END IF;
  END IF;
  IF NULLIF(btrim(_full_name), '') IS NULL OR length(btrim(_full_name)) > 120 THEN
    RAISE EXCEPTION 'Enter a valid full name.';
  END IF;

  UPDATE public.profiles
  SET full_name = btrim(_full_name), role = _role, dealership_id = _dealership_ids[1]
  WHERE id = _target_user_id;
  DELETE FROM public.profile_dealerships WHERE profile_id = _target_user_id;
  INSERT INTO public.profile_dealerships (profile_id, dealership_id)
  SELECT _target_user_id, id FROM unnest(_dealership_ids) AS id;

  INSERT INTO public.audit_events (
    event_type, actor_profile_id, target_profile_id, dealership_id, payload
  ) VALUES (
    'user.access_updated', _actor_user_id, _target_user_id, _dealership_ids[1],
    jsonb_build_object('role', _role, 'dealership_count', cardinality(_dealership_ids))
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_user_activation(
  _actor_id uuid,
  _target_profile_id uuid,
  _status text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target public.profiles%ROWTYPE;
BEGIN
  IF _status NOT IN ('active', 'deactivated') THEN RAISE EXCEPTION 'Invalid status.'; END IF;
  IF _actor_id = _target_profile_id THEN RAISE EXCEPTION 'You cannot change your own activation.'; END IF;
  SELECT * INTO target FROM public.profiles WHERE id = _target_profile_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'User not found'; END IF;
  IF target.role = 'owner'::public.app_role THEN RAISE EXCEPTION 'Owner activation is protected.'; END IF;

  IF NOT (SELECT private.actor_is_active_owner(_actor_id)) THEN
    IF target.role <> 'staff'::public.app_role
       OR target.dealership_id IS NULL
       OR NOT (SELECT private.actor_is_active_dealer_admin_for(_actor_id, target.dealership_id)) THEN
      RAISE EXCEPTION 'Forbidden';
    END IF;
  END IF;
  IF _status = 'active' AND NOT EXISTS (
    SELECT 1 FROM public.dealerships AS d
    WHERE d.id = target.dealership_id
      AND d.status IN ('active', 'trial')
      AND d.subscription_status = 'active'
  ) THEN RAISE EXCEPTION 'The assigned dealership is not active.'; END IF;

  UPDATE public.profiles SET status = _status WHERE id = target.id;
  INSERT INTO public.audit_events (
    event_type, actor_profile_id, target_profile_id, dealership_id, payload
  ) VALUES (
    CASE WHEN _status = 'active' THEN 'user.reactivated' ELSE 'user.deactivated' END,
    _actor_id, target.id, target.dealership_id, jsonb_build_object('status', _status)
  );
END;
$$;

