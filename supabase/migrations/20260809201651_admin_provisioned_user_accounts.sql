-- Admin-provisioned accounts, first-login containment, durable operation
-- reconciliation, and append-only security audit events.
--
-- Passwords are intentionally absent from every database object in this
-- migration. They are generated and returned once by trusted server code.

CREATE TABLE public.user_onboarding (
  profile_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
  onboarding_method text NOT NULL DEFAULT 'pending'
    CHECK (onboarding_method IN ('pending', 'invitation', 'admin_provisioned', 'existing')),
  onboarding_state text NOT NULL DEFAULT 'password_change_required'
    CHECK (onboarding_state IN ('password_change_required', 'complete', 'blocked')),
  password_change_required boolean NOT NULL DEFAULT true,
  credential_issued_at timestamptz,
  password_changed_at timestamptz,
  completed_at timestamptz,
  issued_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (password_change_required AND onboarding_state <> 'complete')
    OR (NOT password_change_required AND onboarding_state = 'complete')
  )
);

-- Existing accounts predate temporary credentials and remain usable.
INSERT INTO public.user_onboarding (
  profile_id,
  onboarding_method,
  onboarding_state,
  password_change_required,
  password_changed_at,
  completed_at
)
SELECT id, 'existing', 'complete', false, now(), now()
FROM public.profiles;

CREATE TABLE public.user_account_operations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  operation_type text NOT NULL
    CHECK (operation_type IN ('admin_provision', 'temporary_password_reset')),
  idempotency_key uuid NOT NULL,
  target_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  target_email text NOT NULL,
  requested_full_name text,
  requested_role public.app_role,
  primary_dealership_id uuid REFERENCES public.dealerships(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'requested'
    CHECK (status IN (
      'requested', 'auth_pending', 'auth_updated', 'complete',
      'needs_reconciliation', 'failed', 'compensated'
    )),
  safe_error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  UNIQUE (actor_profile_id, idempotency_key)
);

CREATE TABLE public.user_account_operation_dealerships (
  operation_id uuid NOT NULL REFERENCES public.user_account_operations(id) ON DELETE CASCADE,
  dealership_id uuid NOT NULL REFERENCES public.dealerships(id) ON DELETE RESTRICT,
  position smallint NOT NULL CHECK (position > 0),
  PRIMARY KEY (operation_id, dealership_id),
  UNIQUE (operation_id, position)
);

CREATE TABLE public.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type text NOT NULL CHECK (length(event_type) BETWEEN 3 AND 120),
  actor_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  target_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  dealership_id uuid REFERENCES public.dealerships(id) ON DELETE SET NULL,
  request_id uuid,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX user_account_operations_target_profile_idx
  ON public.user_account_operations (target_profile_id, created_at DESC);
CREATE INDEX user_account_operations_reconciliation_idx
  ON public.user_account_operations (status, updated_at)
  WHERE status IN ('auth_pending', 'auth_updated', 'needs_reconciliation');
CREATE INDEX user_account_operation_dealerships_dealership_idx
  ON public.user_account_operation_dealerships (dealership_id, operation_id);
CREATE INDEX audit_events_actor_occurred_idx
  ON public.audit_events (actor_profile_id, occurred_at DESC);
CREATE INDEX audit_events_target_occurred_idx
  ON public.audit_events (target_profile_id, occurred_at DESC)
  WHERE target_profile_id IS NOT NULL;
CREATE INDEX audit_events_dealership_occurred_idx
  ON public.audit_events (dealership_id, occurred_at DESC)
  WHERE dealership_id IS NOT NULL;

