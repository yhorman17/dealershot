  public.integration_connections, public.vehicle_publications
FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.activity_events_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.activity_events, public.payout_rules, public.payout_entries,
  public.integration_connections, public.vehicle_publications TO authenticated;
GRANT ALL ON public.activity_events, public.payout_rules, public.payout_entries,
  public.integration_connections, public.vehicle_publications TO service_role;
GRANT ALL ON SEQUENCE public.activity_events_id_seq TO service_role;

CREATE POLICY "Authorized users view operational activity"
ON public.activity_events FOR SELECT TO authenticated
USING (
  private.current_user_has_store_capability(dealership_id, 'reports')
  OR (actor_profile_id = (SELECT auth.uid()) AND private.current_user_has_active_membership(dealership_id))
);
CREATE POLICY "Authorized users view payout rules"
ON public.payout_rules FOR SELECT TO authenticated
USING (private.current_user_has_store_capability(dealership_id, 'reports'));
CREATE POLICY "Authorized users view payout entries"
ON public.payout_entries FOR SELECT TO authenticated
USING (
  private.current_user_has_store_capability(dealership_id, 'reports')
  OR (employee_id = (SELECT auth.uid()) AND private.current_user_has_store_capability(dealership_id, 'self_reports'))
);
CREATE POLICY "Administrators view integration status"
ON public.integration_connections FOR SELECT TO authenticated
USING (
  private.current_user_is_active_owner()
  OR (dealership_id IS NOT NULL AND private.current_user_has_store_capability(dealership_id, 'settings'))
);
CREATE POLICY "Active members view vehicle publication status"
ON public.vehicle_publications FOR SELECT TO authenticated
USING (private.current_user_can_access_vehicle(vehicle_id));

