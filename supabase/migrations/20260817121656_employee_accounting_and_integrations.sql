CREATE OR REPLACE FUNCTION private.record_media_variant_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  target_vehicle uuid;
  store_id uuid;
BEGIN
  IF NEW.variant_type = 'original' THEN RETURN NEW; END IF;
  SELECT p.vehicle_id, v.dealership_id INTO target_vehicle, store_id
  FROM public.photos AS p JOIN public.vehicles AS v ON v.id = p.vehicle_id
  WHERE p.id = NEW.photo_id;
  PERFORM private.record_activity(
    store_id, target_vehicle, NULL, NEW.created_by,
    'vehicle_media.variant_created', 'Prepared media variant created',
    jsonb_build_object('photo_id', NEW.photo_id, 'variant_id', NEW.id,
                       'variant_type', NEW.variant_type,
                       'processing_provider', NEW.processing_provider)
  );
  RETURN NEW;
END;
$$;

